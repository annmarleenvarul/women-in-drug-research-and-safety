"""Run compiled dbt analyses and save their results as Markdown tables.

Runs inside the airflow-scheduler container (it has psycopg2, the RESEARCH_DB_* variables and
the compiled dbt output). Compile first, then pipe this script in, for example (PowerShell):

    docker compose exec airflow-scheduler /opt/dbt/bin/dbt compile --select path:analyses/semi_structured `
        --project-dir /opt/airflow/dbt --profiles-dir /opt/airflow/dbt `
        --target-path /opt/airflow/dbt-target --log-path /opt/airflow/dbt-logs
    Get-Content scripts/run_analyses.py -Raw | docker compose exec -T airflow-scheduler python - semi_structured
    docker compose cp airflow-scheduler:/opt/airflow/dbt-target/results/semi_structured.md docs/results/

Argument: the sub-folder of dbt/analyses to run ("." = the top-level Q1-Q5 queries).
Output:   /opt/airflow/dbt-target/results/<name>.md
"""
import glob
import os
import sys
from datetime import datetime, timezone
from decimal import Decimal

import psycopg2

TARGET_PATH = os.getenv("DBT_TARGET_PATH", "/opt/airflow/dbt-target")
PROJECT = "women_drug_safety"
MAX_ROWS = 50  # keep tables readable in the README


def fmt(value):
    if value is None:
        return ""
    if isinstance(value, Decimal):
        value = float(value)
    if isinstance(value, float):
        return f"{value:,.2f}".rstrip("0").rstrip(".")
    return str(value).replace("|", "\\|").replace("\n", " ")


def leading_comments(sql):
    """The '--' comment lines at the top of an analysis describe what it answers."""
    lines = []
    for line in sql.strip().splitlines():
        if not line.startswith("--"):
            break
        lines.append(line[2:].strip())
    return " ".join(lines)


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else "."
    pattern = os.path.join(TARGET_PATH, "compiled", PROJECT, "analyses", folder, "*.sql")
    files = sorted(glob.glob(pattern))
    if not files:
        sys.exit(f"No compiled analyses at {pattern}. Run dbt compile first.")

    connection = psycopg2.connect(
        host=os.environ["RESEARCH_DB_HOST"],
        port=os.environ.get("RESEARCH_DB_PORT", "5432"),
        user=os.environ["RESEARCH_DB_USER"],
        password=os.environ["RESEARCH_DB_PASSWORD"],
        dbname=os.environ["RESEARCH_DB_NAME"],
    )
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [f"<!-- Generated by scripts/run_analyses.py on {stamp}; do not edit by hand. -->", ""]

    with connection, connection.cursor() as cursor:
        for path in files:
            sql = open(path, encoding="utf-8").read()
            name = os.path.splitext(os.path.basename(path))[0]
            cursor.execute(sql)
            columns = [c.name for c in cursor.description]
            rows = cursor.fetchall()

            out.append(f"### {name}")
            out.append("")
            out.append(f"_{leading_comments(sql)}_")
            out.append("")
            out.append("| " + " | ".join(columns) + " |")
            out.append("|" + "---|" * len(columns))
            for row in rows[:MAX_ROWS]:
                out.append("| " + " | ".join(fmt(v) for v in row) + " |")
            if len(rows) > MAX_ROWS:
                out.append(f"\n_First {MAX_ROWS} of {len(rows)} rows._")
            out.append("")
            print(f"{name}: {len(rows)} rows")

    connection.close()

    results_dir = os.path.join(TARGET_PATH, "results")
    os.makedirs(results_dir, exist_ok=True)
    out_name = "queries" if folder == "." else folder.replace("/", "_")
    out_path = os.path.join(results_dir, f"{out_name}.md")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"Saved {out_path}")


if __name__ == "__main__":
    main()
